// Exports the landing-page phrase data for the ES5 lite page.
//
// The modern app bundles src/lib/data/worldwidedogs.json; old browsers never
// run that bundle, so /lite/ loads a plain <script> that assigns the same
// words to window.WAD_DOGS. Only the fields the lite landing renders are
// kept. Generated on build and on dev-server start; gitignored.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "src/lib/data/worldwidedogs.json");
const TARGET = path.join(ROOT, "public/lite/dogs.js");

const WORD_KEYS = ["we", "are", "dogs", "go", "run", "this"];
const META_KEYS = ["fullname", "country", "dialect", "speakers", "dogs_count", "colors"];

/** Trim each language to what the lite page needs. */
function slimLanguage(entry) {
  const slim = {};
  for (const key of WORD_KEYS) {
    slim[key] = entry[key] || "";
    slim[key + "_p"] = entry[key + "_p"] || "";
  }
  for (const key of META_KEYS) {
    if (entry[key] !== undefined) slim[key] = entry[key];
  }
  return slim;
}

/** Write public/lite/dogs.js; returns the number of languages exported. */
export function buildLiteData() {
  const source = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
  const out = {};
  for (const code of Object.keys(source)) out[code] = slimLanguage(source[code]);
  const body =
    "// Generated by scripts/build-lite-data.js from src/lib/data/worldwidedogs.json. Do not edit.\n" +
    "window.WAD_DOGS = " + JSON.stringify(out) + ";\n";
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, body, "utf8");
  return Object.keys(out).length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const count = buildLiteData();
  console.log(`lite-data: exported ${count} languages to public/lite/dogs.js`);
}
