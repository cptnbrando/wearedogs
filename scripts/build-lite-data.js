// Exports site data for the ES5 lite edition (public/lite/).
//
// The modern app bundles src/data and src/lib/data; old browsers never run
// that bundle, so /lite/ loads plain <script> files instead:
//   public/lite/dogs.js       window.WAD_DOGS — the landing words, all 205
//                             languages (loaded at boot, ~85 KB)
//   public/lite/lite-data.js  window.WAD_LITE — music, places, store, blog
//                             posts and letters pre-rendered to HTML
//                             (loaded lazily when a panel opens)
// Generated on build and on dev-server start; both files are gitignored.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { marked } from "marked";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const LANG_SOURCE = path.join(ROOT, "src/lib/data/worldwidedogs.json");
const DOGS_TARGET = path.join(ROOT, "public/lite/dogs.js");
const DATA_TARGET = path.join(ROOT, "public/lite/lite-data.js");
const TRACKS_SOURCE = path.join(ROOT, "src/data/music/tracks.js");
const PLACES_SOURCE = path.join(ROOT, "src/data/map/locations.json");
const REVIEWS_SOURCE = path.join(ROOT, "src/data/map/reviews.json");
const PRODUCTS_SOURCE = path.join(ROOT, "src/data/store/products.json");
const CAMPAIGNS_SOURCE = path.join(ROOT, "src/data/fundraiser/campaigns.json");
const BLOG_DIR = path.join(ROOT, "src/data/blog");
const LETTERS_DIR = path.join(ROOT, "src/data/correspondence");

const WORD_KEYS = ["we", "are", "dogs", "go", "run", "this"];
const META_KEYS = [
  "fullname", "country", "dialect", "speakers", "dogs_count", "colors",
  "humanCBR", "humanCDR", "dogCBR", "dogCDR",
];
const TRACK_KEYS = ["id", "title", "artist", "album", "cover", "altCover", "src", "year", "genre", "attrib"];
const PRODUCT_KEYS = ["id", "title", "price", "sale", "description", "sizes", "inStock", "image", "checkoutUrl"];
const CAMPAIGN_KEYS = ["id", "title", "status", "goal", "raised", "endDateLabel", "finalEndDateLabel", "updateNote", "description", "images"];
const FRONTMATTER_RE = /^﻿?---\r?\n([\s\S]*?)\r?\n---\r?\n?/;

/** Flat frontmatter reader — same rules as scripts/vite-plugin-md-data.js. */
function readFrontmatter(block) {
  const meta = {};
  for (const line of block.split("\n")) {
    const idx = line.indexOf(":");
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    if (!key || key.startsWith("#")) continue;
    meta[key] = line.slice(idx + 1).trim().replace(/\s+#.*$/, "").replace(/^['"]|['"]$/g, "");
  }
  return meta;
}

function pick(entry, keys) {
  const out = {};
  for (const key of keys) if (entry[key] !== undefined) out[key] = entry[key];
  return out;
}

/** Markdown file → { slug, ...frontmatter, html }. */
function renderMarkdown(file) {
  const raw = fs.readFileSync(file, "utf8");
  const match = FRONTMATTER_RE.exec(raw);
  const meta = match ? readFrontmatter(match[1]) : {};
  const body = (match ? raw.slice(match[0].length) : raw).trim();
  return {
    slug: path.basename(file, ".md"),
    ...meta,
    html: marked.parse(body, { gfm: true, async: false }),
  };
}

function markdownDir(dir, skip) {
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith(".md") && !skip.test(name))
    .map((name) => renderMarkdown(path.join(dir, name)))
    .sort((a, b) => String(b.date || "").localeCompare(String(a.date || "")));
}

function slimLanguage(entry) {
  const slim = {};
  for (const key of WORD_KEYS) {
    slim[key] = entry[key] || "";
    slim[key + "_p"] = entry[key + "_p"] || "";
  }
  for (const key of META_KEYS) if (entry[key] !== undefined) slim[key] = entry[key];
  return slim;
}

function scriptFile(globalName, value) {
  return (
    "// Generated by scripts/build-lite-data.js. Do not edit.\n" +
    "window." + globalName + " = " + JSON.stringify(value) + ";\n"
  );
}

/** Write public/lite/dogs.js; returns the number of languages exported. */
export function buildLiteData() {
  const source = JSON.parse(fs.readFileSync(LANG_SOURCE, "utf8"));
  const langs = {};
  for (const code of Object.keys(source)) langs[code] = slimLanguage(source[code]);
  fs.mkdirSync(path.dirname(DOGS_TARGET), { recursive: true });
  fs.writeFileSync(DOGS_TARGET, scriptFile("WAD_DOGS", langs), "utf8");
  return Object.keys(langs).length;
}

/** Write public/lite/lite-data.js; returns counts per section. */
export async function buildLitePanels() {
  // Windows absolute paths are not valid ESM specifiers; go through file://.
  const { fullLibrary } = await import(pathToFileURL(TRACKS_SOURCE).href);
  const reviews = JSON.parse(fs.readFileSync(REVIEWS_SOURCE, "utf8"));
  const places = JSON.parse(fs.readFileSync(PLACES_SOURCE, "utf8")).map((place) => ({
    ...place,
    ...(reviews[place.id] || {}),
  }));
  const data = {
    tracks: fullLibrary.filter((t) => t.public).map((t) => pick(t, TRACK_KEYS)),
    places,
    products: JSON.parse(fs.readFileSync(PRODUCTS_SOURCE, "utf8")).map((p) => pick(p, PRODUCT_KEYS)),
    campaigns: JSON.parse(fs.readFileSync(CAMPAIGNS_SOURCE, "utf8")).map((c) => pick(c, CAMPAIGN_KEYS)),
    posts: markdownDir(BLOG_DIR, /^_/),
    letters: markdownDir(LETTERS_DIR, /^(index|links)\.md$/),
  };
  fs.writeFileSync(DATA_TARGET, scriptFile("WAD_LITE", data), "utf8");
  const counts = {};
  for (const key of Object.keys(data)) counts[key] = data[key].length;
  return counts;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const langCount = buildLiteData();
  const counts = await buildLitePanels();
  console.log(`lite-data: ${langCount} languages → public/lite/dogs.js; ${JSON.stringify(counts)} → public/lite/lite-data.js`);
}
