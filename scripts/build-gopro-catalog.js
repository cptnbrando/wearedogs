// Generates public/gopro/catalog.js for the GoPro-lite TV page.
//
// The TV page is plain ES5 loaded via <script src> — no modules, no fetch —
// so the catalog ships as a window global. Source of truth stays
// src/data/gopro/videos.js and the show-slug map in router.svelte.js;
// this runs in the build chain (package.json "build") so production can
// never drift, and the output is committed so the dev server serves it
// with zero steps.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { catalog } from "../src/data/gopro/videos.js";
import { SHOW_SLUGS } from "../src/lib/router.svelte.js";

const ORIGIN = "https://data.wearedogs.net";

const shows = {};
for (const [name, show] of Object.entries(catalog)) {
  shows[name] = {
    symbol: show.symbol,
    // Absolute URL for production; path for the dev server's /vid proxy.
    baseUrl: show.baseUrl,
    path: show.baseUrl.startsWith(ORIGIN)
      ? show.baseUrl.slice(ORIGIN.length)
      : show.baseUrl,
    episodes: show.episodes.map((e) => ({
      id: e.id,
      title: e.title,
      file: e.file,
    })),
  };
}

const payload = { catalog: shows, slugs: SHOW_SLUGS };

const banner =
  "/* GENERATED by scripts/build-gopro-catalog.js - do not edit.\n" +
  "   Source: src/data/gopro/videos.js + src/lib/router.svelte.js */\n";
const body = "window.WAD_TV = " + JSON.stringify(payload) + ";\n";

const outDir = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "public",
  "gopro",
);
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, "catalog.js");
fs.writeFileSync(outFile, banner + body);

const showCount = Object.keys(shows).length;
const epCount = Object.values(shows).reduce((s, x) => s + x.episodes.length, 0);
console.log(`gopro catalog: ${showCount} shows, ${epCount} episodes -> ${outFile}`);
